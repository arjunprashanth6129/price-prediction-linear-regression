#!/usr/bin/env python3
"""Stage 2: clean the raw prices and report every repair made.

Runs the cleaning in data.py over the full sample and writes
results/strategy/data_quality.md, which lists each removed session, each
restarted history, each spike and each break with the rule that caught it. The
report computes no returns or signals, so it reads the holdout years without
touching the holdout lock.

It also checks that Yahoo's adjusted close includes dividends: the step in the
ratio of adjusted to split-only close accumulates to the dividend yield, so for
a steady payer such as ITC it should come to a few percent a year.

    python3 scripts/strategy/02_clean.py
"""
import sys

from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import data  # noqa: E402

OUT = ROOT / "results" / "strategy" / "data_quality.md"
DIVIDEND_CHECK = "ITC"


def main() -> int:
    panel = data.load_panel(full=True)
    rep = panel.report
    OUT.parent.mkdir(parents=True, exist_ok=True)

    adj = data._read("adj_close.csv.gz")[DIVIDEND_CHECK]
    close = data._read("close.csv.gz")[DIVIDEND_CHECK]
    steps = np.log(adj / close).diff()
    yearly = steps.groupby(steps.index.year).sum()

    first = panel.adj.apply(pd.Series.first_valid_index)
    L = [
        "# Data quality",
        "",
        "Generated by `scripts/strategy/02_clean.py` from the files in "
        "`scripts/strategy/raw/`. The rules are documented in "
        "`scripts/strategy/data.py`.",
        "",
        "## Coverage",
        "",
        f"- Sessions: {len(panel.adj):,}, {panel.adj.index.min().date()} to "
        f"{panel.adj.index.max().date()}",
        f"- Stocks with data: {panel.adj.notna().any().sum()} of the current Nifty 500",
        "",
        "| Year | Stocks with a price at the start of the year |",
        "|---|---:|",
    ]
    for y in range(panel.adj.index.year.min(), panel.adj.index.year.max() + 1):
        L.append(f"| {y} | {int((first <= pd.Timestamp(f'{y}-01-31')).sum())} |")

    L += ["", "## Repairs", "",
          f"- Sparse sessions dropped (rule 1): {len(rep['sparseSessions'])} "
          f"({', '.join(rep['sparseSessions'])})",
          f"- Histories restarted after a suspension of 60+ sessions (rule 2): "
          f"{len(rep['restarts'])}",
          f"- Reverting spikes removed (rule 3): "
          f"{sum(len(v) for v in rep['spikes'].values())} prices in "
          f"{len(rep['spikes'])} stocks",
          f"- Breaks set to a zero return (rule 4): {len(rep['breaks'])}",
          "", "### Restarted histories", "",
          "| Stock | History restarts on | Longest run without a trade |",
          "|---|---|---:|"]
    for t, d, n in rep["restarts"]:
        L.append(f"| {t} | {d or 'never trades again'} | {n} sessions |")

    L += ["", "### Breaks", "",
          "| Date | Stock | Move removed | Rule |", "|---|---|---:|---|"]
    for t, d, move, why in rep["breaks"]:
        L.append(f"| {d} | {t} | {move:+.1%} | {why} |")

    L += ["", "### Spikes", "",
          "| Stock | Sessions removed |", "|---|---|"]
    for t, days in sorted(rep["spikes"].items()):
        L.append(f"| {t} | {', '.join(days)} |")

    L += ["", "## Dividends", "",
          f"Yearly sum of the log step in {DIVIDEND_CHECK}'s adjusted-to-unadjusted "
          "close ratio. Values near the dividend yield confirm that the adjusted "
          "close, and so every return in this study, includes dividends.", "",
          "| Year | Implied dividend yield |", "|---|---:|"]
    for y, v in yearly.items():
        L.append(f"| {y} | {v:.2%} |")

    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L[:30]))
    print(f"... wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
